#!/usr/bin/env bash
# Prints a paste-ready Windows block that forwards the WSL2 fallback app ports
# 8889-8892 from Windows localhost to the current WSL IP via
# `netsh interface portproxy` (show -> delete stale -> add -> show). Run inside
# WSL2, then paste stdout into an ELEVATED Command Prompt — netsh refuses
# add/delete without administrator rights. SPEC V20/V21, T25; the manual flow is
# documented in README.md ("WSL2: Windows browser access on fallback ports").
#
# usage: setup-windows-portproxy.sh [wsl_ip]
#   default wsl_ip: first address of `hostname -I`, same detection the
#   `make run-*` launchers use for the printed Windows-browser URL.
set -euo pipefail

wsl_ip="${1:-}"
if [[ -z "$wsl_ip" ]]; then
  wsl_ip="$(hostname -I 2>/dev/null | awk '{print $1}')"
fi
# strict IPv4 (dotted quads, octets 0-255) on BOTH paths: the value is interpolated
# into a Windows cmd block, so nothing outside [0-9.] may ever reach it
if [[ ! "$wsl_ip" =~ ^([0-9]|[1-9][0-9]|1[0-9][0-9]|2[0-4][0-9]|25[0-5])(\.([0-9]|[1-9][0-9]|1[0-9][0-9]|2[0-4][0-9]|25[0-5])){3}$ ]]; then
  echo "setup-windows-portproxy.sh: could not detect the WSL IPv4 address; find it with 'ip addr' and re-run: setup-windows-portproxy.sh <WSL_IP>" >&2
  exit 1
fi

# stdout = Windows elevated Command Prompt block (rem = cmd comments, %p = interactive paste form)
cat <<EOF
rem mmux-vite WSL2 fallback ports 8889-8892 -> WSL IP $wsl_ip
rem Generated by scripts/setup-windows-portproxy.sh. After 'wsl --shutdown' or a reboot the
rem WSL IP changes and these rules keep forwarding to the OLD address — re-run and re-paste.
netsh interface portproxy show v4tov4
for /L %p in (8889,1,8892) do netsh interface portproxy delete v4tov4 listenaddress=0.0.0.0 listenport=%p
for /L %p in (8889,1,8892) do netsh interface portproxy add v4tov4 listenaddress=0.0.0.0 listenport=%p connectaddress=$wsl_ip connectport=%p
netsh interface portproxy show v4tov4
rem If the rules look right but the Windows browser still cannot connect, Windows Defender
rem Firewall may need an inbound allow (run once):
rem netsh advfirewall firewall add rule name="mmux-vite WSL fallback ports" dir=in action=allow protocol=TCP localport=8889-8892
EOF

cat >&2 <<EOF
setup-windows-portproxy.sh: WSL IP = $wsl_ip
setup-windows-portproxy.sh: paste the block above into an elevated Command Prompt (cmd.exe as Administrator).
setup-windows-portproxy.sh: to tear the rules down without re-adding, run only the 'delete' line.
setup-windows-portproxy.sh: per cmd.exe batch semantics, a saved .cmd file would need '%%p' instead of '%p'; only the interactive-paste form is exercised here — re-check before saving as a batch file.
setup-windows-portproxy.sh: after every WSL restart, rules are stale (old IP) — re-run this script and re-apply.
EOF
