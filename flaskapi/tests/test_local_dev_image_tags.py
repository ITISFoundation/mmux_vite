"""
Regression tests for SPEC.md B27wk/V45wk: `make build*` builds from
docker-compose.yml, whose image tags are NOT in the `.bumpversion.cfg` fan-out
(§V5), so every local build lands `X.Y.Z` while the dev composes and
publish-local demand the full `.devN` stamp `$(DOCKER_IMAGE_TAG)`. The moment
a stamp lands, `make run-develop-*` PULLS a tag that was never built locally
("pull access denied ... may require 'docker login'") and publish-local tags a
nonexistent source. The build recipes must alias every built image to
`$(DOCKER_IMAGE_TAG)` via the `tag-local` step.
"""

import re
from pathlib import Path

import pytest

pytestmark = pytest.mark.unit

REPO_ROOT = Path(__file__).resolve().parents[2]
MAKEFILE = (REPO_ROOT / "Makefile").read_text()

# Same field scope as scripts/auto_version.py FANOUT_FIELDS: that gate runs at
# stamp time only; these pins keep the parity true between stamps too.
IMAGE_TAG_FIELD = re.compile(r"^\s*image:\s*(\S+):(\S+)\s*$", re.MULTILINE)
DOCKER_IMAGE_TAG_FIELD = re.compile(r"^DOCKER_IMAGE_TAG\s*:=\s*(\S+)\s*$", re.MULTILINE)

# Hand-maintained dev conveniences carry the full stamped version (§V5);
# docker-compose.yml is the build compose with the .devN-stripped base tags.
DEV_COMPOSE_FILES = ["docker-compose-development.yml", "docker-compose-local.yml"]


def _make_block(prefix: str) -> str:
    """Makefile stanza starting at `prefix` plus its tab-indented lines."""
    lines = MAKEFILE.splitlines()
    for i, line in enumerate(lines):
        if line.startswith(prefix):
            block = [line]
            for following in lines[i + 1 :]:
                if not following.startswith("\t"):
                    break
                block.append(following)
            return "\n".join(block)
    raise AssertionError(f"Makefile: no stanza starting with {prefix!r}")


def test_v45wk_dev_compose_tags_equal_the_makefile_stamp():
    stamp_match = DOCKER_IMAGE_TAG_FIELD.search(MAKEFILE)
    assert stamp_match, "Makefile must define `DOCKER_IMAGE_TAG := <version>` (V5 stamp site)"
    stamp = stamp_match.group(1)
    for filename in DEV_COMPOSE_FILES:
        content = (REPO_ROOT / filename).read_text()
        for _name, tag in IMAGE_TAG_FIELD.findall(content):
            assert tag == stamp, (
                f"{filename}: image tag {tag!r} drifted from the Makefile stamp "
                f"{stamp!r}; dev composes carry the full .devN version and must "
                "move only through scripts/auto_version.py (§V5)"
            )


def test_v45wk_build_recipes_invoke_the_alias_step():
    for target in ("build:", "build-no-cache:"):
        recipe = _make_block(target)
        assert "tag-local" in recipe, (
            f"Makefile `{target}` recipe must invoke `tag-local` (V45wk): "
            "`docker compose build` tags images with the .devN-stripped base "
            "from docker-compose.yml, so without the alias step the stamped "
            "tag the dev composes and publish-local demand is never produced "
            "(B27wk: `make run-develop-*` fell back to PULLING a never-built "
            "tag and died on 'pull access denied')"
        )


def test_v45wk_tag_local_aliases_every_built_image_without_new_version_literals():
    recipe = _make_block("tag-local:")
    image_list = _make_block("MMUX_LOCAL_IMAGES :=")
    # docker-compose.yml is generated by compose-spec (V7) and ⊥ present on a
    # fresh checkout; the hermetic image universe is §V5's 8 stamp sites:
    # .osparc/flaskapi -> mmux-vite-backend, .osparc/node -> mmux-vite-web,
    # .osparc/proxy-<mode>-<perm> -> mmux-vite-app-<mode>-<perm>.
    built_images = {
        "simcore/services/dynamic/mmux-vite-backend",
        "simcore/services/dynamic/mmux-vite-web",
    }
    built_images |= {
        f"simcore/services/dynamic/mmux-vite-app-{d.name.removeprefix('proxy-')}"
        for d in (REPO_ROOT / ".osparc").iterdir()
        if d.is_dir() and d.name.startswith("proxy-")
    }
    assert len(built_images) == 8, (
        "§V5 expects 8 stamp sites (backend, web, 6 app proxies); got "
        f"{len(built_images)} — revisit this test if the matrix changes"
    )

    assert "docker tag" in recipe, "tag-local must run `docker tag` (V45wk)"
    assert "$(RELEASE_TAG)" in recipe and "$(DOCKER_IMAGE_TAG)" in recipe, (
        "tag-local must alias $(RELEASE_TAG) -> $(DOCKER_IMAGE_TAG) by "
        "variable, never by baked-in tags (V45wk)"
    )
    for name in sorted(built_images):
        assert name in image_list, (
            f"tag-local image list must cover every image docker-compose.yml "
            f"builds; {name} is missing (V45wk)"
        )

    release = _make_block("RELEASE_TAG :=")
    assert "$(DOCKER_IMAGE_TAG)" in release and ".dev" in release, (
        "RELEASE_TAG must be DERIVED from DOCKER_IMAGE_TAG by stripping the "
        ".devN counter, not stamped as a second literal to drift (V45wk)"
    )
    literals = re.findall(r"\d+\.\d+\.\d+", release + image_list + recipe)
    assert not literals, (
        f"V45wk: the alias machinery must carry no literal version "
        f"(found {literals}); single source is DOCKER_IMAGE_TAG per .bumpversion.cfg"
    )

    # GH-Copilot #718 (B28qm): /bin/sh exits a for-loop with the LAST command's
    # status, so an unguarded mid-loop `docker tag` failure is masked whenever
    # the final image aliases fine — build reports success with stamps missing.
    assert re.search(r"docker tag[^\n]*\|\| exit 1", recipe), (
        "tag-local must fail fatally on the first failed docker tag (B28qm): "
        "under /bin/sh a for-loop returns the last command's status, masking "
        "missing aliases exactly when the final image succeeds (V45wk "
        "forbids recipe paths that leave the stamped tag unproduced)"
    )
